COUNTRY_CODE_TO_NAME = dict(COUNTRIES)


def get_country_name(code_or_name: str) -> str:
    """
    Retourne le nom français complet d'un pays à partir de son code ISO alpha-2 ou de son nom.
    Ex: 'FR' -> 'France', 'France' -> 'France', 'ES' -> 'Espagne'.
    """
    if not code_or_name:
        return ""
    code_upper = code_or_name.strip().upper()
    return COUNTRY_CODE_TO_NAME.get(code_upper, code_or_name.strip())
